import { expect, test } from '@playwright/test';
import { signUp } from './helpers';

test('synthetic bands-only policy prioritises only when ranking is permitted', async ({ page }) => {
  await signUp(page);
  await page.evaluate(() => (window as any).__garageMock.seedBandPriorityCases());
  await page.goto('/app/bookings');
  await expect(page.getByText(/Fixture simulation — all vehicle histories/)).toBeVisible();
  const ranked = page.getByRole('region', { name: /highest priority first/i });
  await expect(ranked.getByRole('link', { name: 'DEMO01' })).toBeVisible();
  await expect(ranked.getByRole('link', { name: 'DEMO04' })).toBeVisible();
  await expect(ranked.getByRole('link', { name: 'DEMO02' })).toHaveCount(0);
  const rows = ranked.getByTestId('booking-row');
  expect(await rows.evaluateAll(els => els.map(e => e.getAttribute('data-reg')))).toEqual(['DEMO01', 'DEMO04']);
  await expect(rows.first().getByTestId('band-estimate')).toHaveText('High band');
  await expect(rows.first()).not.toContainText('%');
  await expect(ranked).not.toContainText('Each percentage');
  const unranked = page.getByRole('region', { name: /not ranked yet/i });
  await expect(unranked.getByRole('link', { name: 'DEMO02' })).toBeVisible();
  await expect(unranked.getByTestId('band-estimate')).toHaveText('Medium band');
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.screenshot({ path: 'screenshots/5-bands-priority.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'screenshots/5-bands-priority-phone.png', fullPage: true });
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole('link', { name: 'DEMO01' }).click();
  await expect(page.getByRole('heading', { name: 'Briefing for DEMO01' })).toBeVisible();
  const estimate = page.getByRole('region', { name: 'Estimate' });
  await expect(estimate).toContainText('High band');
  await expect(estimate).toContainText('A percentage is not available');
  await expect(estimate).not.toContainText('%');
  await page.getByRole('link', { name: 'Back to bookings' }).click();
  await page.getByRole('link', { name: 'DEMO02' }).click();
  const disabledEstimate = page.getByRole('region', { name: 'Estimate' });
  await expect(disabledEstimate).toContainText('Medium band');
  await expect(disabledEstimate).toContainText('A percentage is not available');
  await expect(disabledEstimate).not.toContainText('%');
});
