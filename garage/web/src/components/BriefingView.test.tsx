import { describe, expect, it, vi } from 'vitest';
import { render, screen, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { MemoryRouter } from 'react-router-dom';
import { BriefingView } from './BriefingView';
import { demoBookings, demoBriefingFor } from '../mocks/fixtures';
import fixtures from '../mocks/briefingFixtures.json';
import type { Briefing } from '../api/types';
import { FEEDBACK_REASON_LABEL } from './FeedbackControl';

type Props = React.ComponentProps<typeof BriefingView>;
const setup = (idx = 0, extra: Partial<Props> = {}) => {
  const booking = demoBookings('2026-10-26')[idx];
  const onDecide = vi.fn().mockResolvedValue(undefined);
  const onFeedback = vi.fn().mockResolvedValue(undefined);
  render(
    <MemoryRouter>
      <BriefingView booking={booking} decisions={[]} briefing={demoBriefingFor(booking, '2026-10-26', 1)} backTo="/x" onDecide={onDecide} onFeedback={onFeedback} {...extra} />
    </MemoryRouter>,
  );
  return { onDecide, onFeedback };
};

describe('BriefingView', () => {
  it('shows the service-supplied estimate with the required wording', () => {
    setup();
    const card = within(screen.getByRole('region', { name: 'Estimate' }));
    expect(card.getByText('45%')).toBeInTheDocument();
    expect(card.getByText('High')).toBeInTheDocument();
    expect(card.getByText('estimated chance of failing or needing rectification during the MOT')).toBeInTheDocument();
    expect(card.getByText(/not an inspection, a diagnosis or a guarantee/i)).toBeInTheDocument();
    expect(card.getByText(/strictly before 26 Oct 2026/)).toBeInTheDocument();
    expect(card.getByText(/assessment version 1/)).toBeInTheDocument();
  });
  it('shows the dated evidence summary from the assessment', () => {
    setup();
    const dl = within(screen.getByTestId('evidence-summary'));
    expect(dl.getByText('Earlier tests used')).toBeInTheDocument();
    expect(dl.getByText('3')).toBeInTheDocument();
    expect(dl.getByText('Most recent earlier test')).toBeInTheDocument();
  });
  it('shows dated source records and presents recorded advisories as history, never as current defects', () => {
    setup();
    const recs = within(screen.getByTestId('source-records'));
    expect(recs.getAllByText(/historical/i).length).toBeGreaterThan(0);
    expect(recs.getByText(/Front brake disc worn/)).toBeInTheDocument();
    expect(recs.getAllByText(/^Advisory, recorded at test on \d+ \w+ \d{4}:$/).length).toBeGreaterThan(0);   // every defect is typed and dated
    expect(screen.queryByText(/current defects?/i)).toBeNull();
    expect(screen.queryByText(/currently (has|have|needs)/i)).toBeNull();
    expect(screen.getByText(/history, not a list of what is wrong now/i)).toBeInTheDocument();
    expect(recs.getAllByRole('time').length).toBe(3);
  });
  it('lists evidence gaps and rule-generated follow-up questions', () => {
    setup();
    expect(within(screen.getByTestId('evidence-gaps')).getAllByRole('listitem').length).toBeGreaterThan(0);
    expect(within(screen.getByTestId('follow-ups')).getAllByRole('listitem')).toHaveLength(2);
    expect(screen.getByText(/Generated by fixed rules/)).toBeInTheDocument();
    expect(screen.getByTestId('briefing-summary')).toHaveTextContent(/^Recorded before 26 October 2026: 3 MOT test results\./);
  });
  it('when the briefing could not be loaded, says so and adds an evidence gap', () => {
    setup(0, { briefing: null });
    expect(screen.queryByTestId('source-records')).toBeNull();
    expect(screen.getByText(/No follow-up questions are available/)).toBeInTheDocument();
    expect(within(screen.getByTestId('evidence-gaps')).getByText(/briefing could not be loaded/)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Helpful' })).toBeDisabled();           // nothing to give feedback on
  });
  it('shows the service-supplied rounding step, band edges and the provisional marker', () => {
    setup();
    const card = within(screen.getByRole('region', { name: 'Estimate' }));
    expect(card.getByText(/Rounded to the nearest 5 percentage points by the service\./)).toBeInTheDocument();
    expect(card.getByTestId('band-legend')).toHaveTextContent('Bands: Low under 20%; Medium 20% to under 35%; High 35% or more.');
    expect(card.getByTestId('band-legend')).toHaveTextContent('provisional');
  });
  it('uses the band label the service gave, not a client table', () => {
    const booking = demoBookings('2026-10-26')[0];
    const a = { ...booking.assessment!, display_policy: { ...booking.assessment!.display_policy!, band_labels: { low: 'L', medium: 'M', high: 'Elevated' }, provisional: false } };
    render(<MemoryRouter><BriefingView booking={{ ...booking, assessment: a }} decisions={[]} briefing={null} backTo="/x" onDecide={vi.fn()} onFeedback={vi.fn()} /></MemoryRouter>);
    expect(within(screen.getByTestId('estimate')).getByText('Elevated')).toBeInTheDocument();
    expect(screen.getByTestId('band-legend')).not.toHaveTextContent('provisional');
  });
  it('shows the appointment time next to the date when there is one', () => {
    const booking = { ...demoBookings('2026-10-26')[0], appointment_time: '09:30' };
    render(<MemoryRouter><BriefingView booking={booking} decisions={[]} briefing={null} backTo="/x" onDecide={vi.fn()} onFeedback={vi.fn()} /></MemoryRouter>);
    expect(screen.getByTestId('appointment-time')).toHaveTextContent('09:30');
  });
  it('has no LLM or rewrite control (R8)', () => {
    setup();
    expect(screen.queryByRole('button', { name: /rewrite|rephrase|ai |generate|summar|chatgpt|gpt/i })).toBeNull();
  });
  it('for a non-available booking shows the state and reason instead of an estimate', () => {
    setup(6);
    expect(screen.queryByTestId('estimate')).toBeNull();
    expect(screen.getAllByText(/No earlier MOT test is recorded/).length).toBeGreaterThan(0);
    expect(screen.getByText(/No individual test records/)).toBeInTheDocument();
    expect(within(screen.getByTestId('evidence-gaps')).getByText(/No earlier MOT test is recorded/)).toBeInTheDocument();
  });
  it('offers the four contract decision options plus a note, and submits them', async () => {
    const u = userEvent.setup();
    const { onDecide } = setup();
    expect(screen.getAllByRole('radio').map((r) => r.getAttribute('value'))).toEqual(['check_repair_history', 'offer_inspection', 'adjust_booking_plan', 'proceed_as_booked']);
    expect(screen.getByRole('button', { name: 'Save decision' })).toBeDisabled();
    await u.click(screen.getByRole('radio', { name: /Offer an inspection/ }));
    await u.type(screen.getByLabelText(/Short note/), 'Bay 2');
    await u.click(screen.getByRole('button', { name: 'Save decision' }));
    expect(onDecide).toHaveBeenCalledWith('offer_inspection', 'Bay 2');
  });
  it('caps the note at the contract limit (500) and warns against customer details', () => {
    setup();
    expect(screen.getByLabelText(/Short note/)).toHaveAttribute('maxlength', '500');
    expect(screen.getByText(/Don't include customer names, phone numbers or other customer details\./)).toBeInTheDocument();
  });
  it('renders the decision history with who and when', () => {
    const decisions = [{ id: 'd1', booking_id: 'b', decision_type: 'proceed_as_booked' as const, note: 'Fine', actor: { membership_id: 'm', email: 'a@x.test', role: 'staff' as const }, created_at: '2026-10-26T09:30:00+00:00' }];
    setup(0, { decisions });
    const item = screen.getByTestId('decision-item');
    expect(item).toHaveTextContent('Proceed as booked');
    expect(item).toHaveTextContent('By a@x.test on 26 Oct 2026, 09:30');
  });
  it('feedback is optional and toggles helpful / not helpful, with an optional reason', async () => {
    const u = userEvent.setup();
    const { onFeedback } = setup();
    await u.click(screen.getByRole('button', { name: 'Not helpful' }));
    expect(onFeedback).toHaveBeenCalledWith('not_helpful', null);
    expect(await screen.findByRole('button', { name: 'Not helpful' })).toHaveAttribute('aria-pressed', 'true');
    expect(screen.getByRole('button', { name: 'Helpful' })).toHaveAttribute('aria-pressed', 'false');
    await u.selectOptions(screen.getByLabelText(/What was wrong/), 'too_long');
    expect(onFeedback).toHaveBeenLastCalledWith('not_helpful', 'too_long');
    await u.click(screen.getByRole('button', { name: 'Helpful' }));
    expect(onFeedback).toHaveBeenLastCalledWith('helpful', null);
    expect(screen.queryByLabelText(/What was wrong/)).toBeNull();                  // no reason for helpful
    expect(Object.keys(FEEDBACK_REASON_LABEL)).toHaveLength(5);
  });
  it('shows the member\'s earlier feedback on this briefing version', () => {
    const booking = demoBookings('2026-10-26')[0];
    const br = { ...demoBriefingFor(booking, '2026-10-26', 1), feedback: { value: 'not_helpful' as const, reason_code: 'too_long' as const, briefing_version: 'x', assessment_version: 1, updated_at: '2026-10-26T09:00:00+00:00' } };
    render(<MemoryRouter><BriefingView booking={booking} decisions={[]} briefing={br} backTo="/x" onDecide={vi.fn()} onFeedback={vi.fn()} /></MemoryRouter>);
    expect(screen.getByRole('button', { name: 'Not helpful' })).toHaveAttribute('aria-pressed', 'true');
    expect(screen.getByLabelText(/What was wrong/)).toHaveValue('too_long');
  });
  it('refresh appears for MOT bookings with a handler, not for retests, and is disabled while pending', async () => {
    const onRefresh = vi.fn().mockResolvedValue(undefined);
    setup(0, { onRefresh });
    await userEvent.setup().click(screen.getByRole('button', { name: 'Refresh assessment' }));
    expect(onRefresh).toHaveBeenCalled();
  });
  it('no refresh for a retest or a cancelled booking', () => {
    setup(8, { onRefresh: vi.fn() });
    expect(screen.queryByRole('button', { name: 'Refresh assessment' })).toBeNull();
  });
  it('says the estimate is for workshop staff only', () => {
    setup();
    expect(screen.getByTestId('staff-only')).toHaveTextContent('For workshop staff only. Not a defect finding.');
  });
  it('offers no print, share, export, copy-link or customer view of the estimate', () => {
    setup();
    expect(screen.queryByRole('button', { name: /print|share|export|download|copy link|send to|email (the )?customer|customer view/i })).toBeNull();
    expect(screen.queryByRole('link', { name: /print|share|export|download|customer view/i })).toBeNull();
  });
  it.each([[5, 'unavailable'], [6, 'unsupported'], [7, 'failed'], [4, 'pending']])('a decision can still be recorded when the estimate is not available (booking %i, %s)', async (idx, state) => {
    const u = userEvent.setup();
    const { onDecide } = setup(idx);
    expect(screen.queryByTestId('estimate')).toBeNull();
    await u.click(screen.getByRole('radio', { name: /Proceed as booked/ }));
    await u.click(screen.getByRole('button', { name: 'Save decision' }));
    expect(onDecide).toHaveBeenCalledWith('proceed_as_booked', '');
    expect(state).toBeTruthy();
  });
  it('lists earlier assessment versions when there are several', () => {
    const b = demoBookings('2026-10-26')[0];
    const v2 = { ...b.assessment!, id: 'x2', version: 2 };
    setup(0, { versions: [v2, b.assessment!] });
    expect(screen.getByText('Assessment versions (2)')).toBeInTheDocument();
  });
});


// ---- real briefings: the backend engine's output for the T1b-shaped fixtures --------------------------------
const FX = fixtures as unknown as Record<string, Briefing & { briefing_version: string }>;
const ready = (reg: string): Briefing => ({ ...FX[reg], booking_id: 'b', status: 'ready', reason: null, reason_text: null, assessment_id: 'a', assessment_version: 1, feedback: null });
const rectified = Object.keys(FX).filter((k) => k.startsWith('ZZ') && FX[k].source_records.some((r) => r.result === 'RECTIFIED'));

describe('BriefingView on real engine output', () => {
  const view = (br: Briefing | null) => {
    const booking = demoBookings('2026-10-26')[0];
    render(<MemoryRouter><BriefingView booking={booking} decisions={[]} briefing={br} backTo="/x" onDecide={vi.fn()} onFeedback={vi.fn()} /></MemoryRouter>);
    return booking;
  };
  it('there are fixtures with a rectified-at-the-test event to show', () => {
    expect(rectified.length).toBeGreaterThan(3);
  });
  it('a PRS fail plus its pass is ONE record, "rectified at the test", with its rectified items dated', () => {
    const reg = rectified[0];
    const br = ready(reg);
    view(br);
    const recs = within(screen.getByTestId('source-records'));
    const items = recs.getAllByRole('listitem').filter((li) => li.getAttribute('data-result'));
    expect(items).toHaveLength(br.source_records.length);                         // one list item per event, no separate pass row
    const rect = items.find((li) => li.getAttribute('data-result') === 'RECTIFIED')!;
    expect(rect).toHaveTextContent('Failed items rectified at the test, then passed');
    expect(rect).toHaveTextContent(/Defect rectified at the test, recorded at test on \d+ \w+ \d{4}/);
    expect(rect).not.toHaveTextContent(/^\S+ \S+ \S+ · Failed ·/);
  });
  it('defect wording is shown as a quotation of the source, with the dated label before it', () => {
    const reg = Object.keys(FX).find((k) => FX[k].source_records.some((r) => r.defects.length > 0))!;
    const br = ready(reg);
    view(br);
    const d = br.source_records.find((r) => r.defects.length)!.defects[0];
    expect(screen.getAllByText((_, el) => el?.tagName === 'LI' && (el.textContent ?? '').includes(`${d.label}: \u201c${d.text}\u201d`)).length).toBeGreaterThan(0);
  });
  it('shows the service\'s evidence gaps (here: forced stale history) and its follow-up questions with their source dates', () => {
    const reg = Object.keys(FX).find((k) => FX[k].follow_up_questions.length > 0)!;
    const br: Briefing = { ...ready(reg), evidence_gaps: [{ rule_id: 'G04_stale_history', text: 'The most recent MOT test recorded before 26 October 2026 was on 1 May 2024, more than 15 months earlier.' }] };
    view(br);
    expect(within(screen.getByTestId('evidence-gaps')).getByText(/more than 15 months earlier/)).toBeInTheDocument();
    const qs = within(screen.getByTestId('follow-ups')).getAllByRole('listitem');
    expect(qs).toHaveLength(br.follow_up_questions.length);
    expect(qs[0]).toHaveTextContent(br.follow_up_questions[0].text);
    expect(qs[0]).toHaveTextContent(/From the test on/);
    expect(screen.getByTestId('briefing-provenance')).toHaveTextContent(`Briefing ${br.briefing_version}`);
  });
  it('a vehicle with no history shows the explicit gap instead of an empty briefing', () => {
    view(ready('__not_found__'));
    expect(within(screen.getByTestId('evidence-gaps')).getByText('No MOT history was returned for this registration.')).toBeInTheDocument();
    expect(screen.getByText(/No individual test records/)).toBeInTheDocument();
  });
  it('never presents a historical defect as current, on any of the 50 real briefings', () => {
    for (const reg of Object.keys(FX).filter((k) => k.startsWith('ZZ'))) {
      const { unmount } = render(<MemoryRouter><BriefingView booking={demoBookings('2026-10-26')[0]} decisions={[]} briefing={ready(reg)} backTo="/x" onDecide={vi.fn()} onFeedback={vi.fn()} /></MemoryRouter>);
      expect(screen.queryByText(/current defects?|currently (has|have|needs)|outstanding defects?/i), reg).toBeNull();
      expect(screen.getByText(/history, not a list of what is wrong now/i)).toBeInTheDocument();
      unmount();
    }
  });
});
